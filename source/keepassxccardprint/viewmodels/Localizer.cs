    public static string ResolveLanguage(string selected)
    {
        if (selected is "ru" or "uk" or "en") return selected;
        return CultureInfo.CurrentUICulture.TwoLetterISOLanguageName is "ru" or "uk"
            ? CultureInfo.CurrentUICulture.TwoLetterISOLanguageName : "en";
    }

    public static string Text(string language, string key)
    {
        if (!Lines.TryGetValue(key, out var values)) return key;
        return ResolveLanguage(language) switch
        {
            "uk" => values.Uk,
            "en" => values.En,
            _ => values.Ru
        };
    }
